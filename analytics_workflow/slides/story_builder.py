    analysis = workflow_state.get("analysis_results", {}) or {}
    structured = list(analysis.get("analysis_artifacts", []) or []) + list(analysis.get("chart_specs", []) or [])
    if any(
        isinstance(item, dict)
        and compact_whitespace(item.get("chart_type")).lower() != "decision_tree"
        and any(compact_whitespace(item.get(key)) for key in ("finding", "takeaway", "title"))
        for item in structured
    ):
        return True
    captions = analysis.get("figure_captions", {}) or {}
    if isinstance(captions, dict) and any(compact_whitespace(value) for value in captions.values()):
        return True
    for item in analysis.get("business_findings", []) or []:
        text = compact_whitespace(item).lower()
        if text and "tree" not in text and "model rule" not in text:
            return True
    return False


