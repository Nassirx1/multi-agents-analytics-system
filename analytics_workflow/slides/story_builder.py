def _visual_relevance_score(spec: Any) -> int:
    if not isinstance(spec, dict):
        return 0
    text = " ".join(
        compact_whitespace(spec.get(key)).lower()
        for key in ("artifact_id", "id", "chart_type", "title", "finding", "takeaway", "x", "y", "group_by")
    )
    score = 0
    for token, weight in (
        ("price trend", 10),
        ("moving average", 10),
        ("volatility", 9),
        ("drawdown", 9),
        ("seasonal", 7),
        ("return distribution", 7),
        ("volume spike", 6),
        ("default", 10),
        ("attrition", 10),
        ("depression", 10),
        ("risk", 8),
        ("target", 7),
        ("loan grade", 7),
        ("previous default", 7),
        ("loan percent income", 6),
        ("department", 7),
        ("overtime", 7),
        ("job satisfaction", 7),
        ("environment satisfaction", 6),
        ("work life balance", 6),
        ("sales representative", 6),
        ("years at company", 5),
        ("interest", 5),
        ("income", 4),
        ("rate", 3),
    ):
        if token in text:
            score += weight
    if "age" in text and not any(token in text for token in ("default", "attrition", "depression", "risk")):
        score -= 6
    if "multi-panel" in text or "small multiple" in text or "segment chart" in text:
        score -= 10
    if "scatter" in text or "volume-return" in text or "correlation" in text:
        score -= 8
    return score


def _figure_visual_priority(workflow_state: dict[str, Any], figure: Any, caption: str) -> int:
    text = f"{Path(str(figure)).name} {caption}".lower()
    if _is_stock_time_series_context(workflow_state):
        if any(token in text for token in ("price trend", "moving average", "support", "resistance")):
            return 0
        if any(token in text for token in ("volume spike", "volume trend", "price-volume", "liquidity")):
            return 1
        if any(token in text for token in ("return distribution", "daily return", "seasonal", "monthly return")):
            return 2
        if any(token in text for token in ("volatility", "drawdown")):
            return 3
        if any(token in text for token in ("scatter", "volume-return", "correlation")):
            return 25
    if _is_lending_context(workflow_state):
        return _analysis_visual_priority({"title": text, "chart_type": "code_figure"})
    return 10


def _decision_tree_structured_valid(spec: dict[str, Any]) -> bool:
    data = spec.get("data", {}) if isinstance(spec.get("data"), dict) else {}
    nodes = [node for node in data.get("nodes", []) if isinstance(node, dict)]
    edges = [edge for edge in data.get("edges", []) if isinstance(edge, dict)]
    if not nodes or not edges:
        return False
    node_ids = {compact_whitespace(node.get("id") or node.get("node_id") or node.get("name")) for node in nodes}
    source_ids = {compact_whitespace(edge.get("source") or edge.get("from") or edge.get("parent")) for edge in edges}
    target_ids = {compact_whitespace(edge.get("target") or edge.get("to") or edge.get("child")) for edge in edges}
    leaves = [
        node
        for node in nodes
        if compact_whitespace(node.get("id") or node.get("node_id") or node.get("name")) not in source_ids
    ]
    has_split = any(
        compact_whitespace(node.get("type")).lower() == "split"
        or compact_whitespace(node.get("id") or node.get("node_id") or node.get("name")) in source_ids
        for node in nodes
    )
    return bool(node_ids and target_ids.issubset(node_ids) and has_split and len(leaves) >= 2)


def _caption_for_figure(path: Any, captions: dict[str, Any]) -> str:
    if not isinstance(captions, dict):
        return ""
    figure_path = Path(str(path))
    for key in (path, str(path), figure_path.name, figure_path.stem):
        text = compact_whitespace(captions.get(key))
        if text:
            return text
    return ""


def _figure_title(path: Any, caption: str) -> str:
    if caption:
        first_sentence = caption.split(". ", 1)[0].strip().rstrip(".")
        if first_sentence:
            return shorten(first_sentence, 80)
    return Path(str(path)).stem.replace("_", " ").title()


def _visual_has_data(visual: VisualSpec) -> bool:
    if isinstance(visual.data, list) and visual.data:
        return True
    if isinstance(visual.data, dict) and any(isinstance(visual.data.get(key), list) and visual.data.get(key) for key in ("rows", "data", "values")):
        return True
    if isinstance(visual.series, list) and visual.series:
        return True
    return False


def _analysis_findings(workflow_state: dict[str, Any]) -> list[str]:
    analysis = workflow_state.get("analysis_results", {}) or {}
    findings: list[str] = []
    tree_present = any(
        isinstance(artifact, dict) and compact_whitespace(artifact.get("chart_type")).lower() == "decision_tree"
        for artifact in (analysis.get("analysis_artifacts", []) or []) + (analysis.get("chart_specs", []) or [])
    )
    for artifact in analysis.get("analysis_artifacts", []) or analysis.get("chart_specs", []) or []:
        if isinstance(artifact, dict):
            if compact_whitespace(artifact.get("chart_type")).lower() == "decision_tree":
                visual = VisualSpec.from_any({"type": "structured_chart", **artifact})
                if visual:
                    headline = _decision_tree_visual_headline(visual)
                    data = visual.data if isinstance(visual.data, dict) else {}
                    note = first_nonempty(data.get("performance_note"), decision_tree_performance_note(data))
                    findings.extend(item for item in (headline, note) if compact_whitespace(item))
                continue
            for key in ("finding", "takeaway", "title"):
                text = compact_whitespace(artifact.get(key))
                if text:
                    findings.append(text)
                    break
    for item in analysis.get("business_findings", []) or []:
        text = compact_whitespace(item)
        if tree_present and "tree" in text.lower():
            continue
        if text:
            findings.append(text)
    summary = analysis.get("analysis_summary", {}) or {}
    if isinstance(summary, dict):
        for key, value in summary.items():
            if isinstance(value, (dict, list)):
                continue
            findings.append(f"{str(key).replace('_', ' ').title()}: {compact_whitespace(value)}")
    captions = analysis.get("figure_captions", {}) or {}
    if isinstance(captions, dict):
        findings.extend(compact_whitespace(value) for value in captions.values() if compact_whitespace(value))
    if not findings:
        findings.append("The analysis output did not include structured findings; use available summaries as directional evidence.")
    return refine_bullets(findings, max_items=8, max_chars=140)


def _summary_metrics(workflow_state: dict[str, Any]) -> list[dict[str, str]]:
    metrics: list[dict[str, str]] = []
    summary = workflow_state.get("analysis_results", {}).get("analysis_summary", {}) or {}
    if isinstance(summary, dict):
        for key, value in summary.items():
            if isinstance(value, (int, float)) and not isinstance(value, bool):
                metrics.append({"label": str(key).replace("_", " ").title(), "value": f"{value:g}"})
            elif isinstance(value, str) and any(char.isdigit() for char in value):
                metrics.append({"label": str(key).replace("_", " ").title(), "value": shorten(value, 26)})
            if len(metrics) >= 4:
                break
    return metrics


def _choose_template(existing: SlideSpec | None, visual: VisualSpec | None, fallback_template: str) -> str:
    if visual and visual.type == "structured_chart" and visual.recommended_template in TEMPLATE_REGISTRY:
        return visual.recommended_template or fallback_template
    if existing and existing.template:
        return existing.template
    return fallback_template


def _template_for_visual(visual: VisualSpec | None, offset: int) -> str:
    if visual and visual.type == "structured_chart":
        return visual.recommended_template if visual.recommended_template in TEMPLATE_REGISTRY else _template_for_chart_type(visual.chart_type)
    if visual and visual.type in {"code_figure", "legacy_image_fallback"}:
        return "full_width_chart_takeaway"
    return ANALYSIS_TEMPLATE_SEQUENCE[offset % len(ANALYSIS_TEMPLATE_SEQUENCE)]


def _template_for_chart_type(chart_type: str) -> str:
    normalized = compact_whitespace(chart_type).lower()
    return {
        "small_multiples_bar": "small_multiples_with_takeaway",
        "bar": "single_bar_chart_with_insight",
        "column": "single_bar_chart_with_insight",
        "horizontal_bar": "horizontal_bar_ranking",
        "line": "comparison_chart_with_interpretation",
        "scatter": "comparison_chart_with_interpretation",
        "distribution": "distribution_with_callout",
        "metric_cards": "metric_cards_with_chart",
        "decision_tree": "full_width_chart_takeaway",
    }.get(normalized, "comparison_chart_with_interpretation")


def _analysis_limitations(summary: Any) -> list[str]:
    if not isinstance(summary, dict):
        return []
    limitations: list[str] = []
    for key, value in summary.items():
        lowered = str(key).lower()
        if any(token in lowered for token in ("limitation", "caution", "assumption", "missing", "quality", "note")):
            text = compact_whitespace(value)
            if text:
                limitations.append(text)
    return limitations


def _headline_has_unsupported_ratio(headline: str, evidence_text: str) -> bool:
    return bool(
        re.search(r"\b\d+(?:\.\d+)?x\b", compact_whitespace(headline).lower())
        and "%" in compact_whitespace(evidence_text)
        and not re.search(r"\b\d+(?:\.\d+)?x\b", compact_whitespace(evidence_text).lower())
    )
