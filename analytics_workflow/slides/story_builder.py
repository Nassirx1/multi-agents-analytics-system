def _merge_slide(existing: SlideSpec | None, fallback: SlideSpec) -> SlideSpec:
    if not existing:
        return fallback
    fallback.headline = refine_headline(existing.headline, fallback.headline)
    fallback.main_message = first_nonempty(existing.main_message, fallback.main_message)
    fallback.subtitle = first_nonempty(existing.subtitle, fallback.subtitle)
    if existing.content_blocks:
        fallback.content_blocks = existing.content_blocks
    if existing.visual:
        if fallback.visual and fallback.visual.type == "code_figure":
            pass
        elif fallback.visual and fallback.visual.type in {"structured_chart", "chart"}:
            if existing.visual.type in {"image", "legacy_image_fallback"}:
                pass
            elif existing.visual.type in {"structured_chart", "chart"} and _visual_has_data(existing.visual):
                fallback.visual = existing.visual
        else:
            if _legacy_visual_can_attach(existing.visual, fallback):
                fallback.visual = existing.visual
    if existing.metrics:
        fallback.metrics = existing.metrics
    return fallback


def _polish_deck_slides(deck: DeckSpec) -> None:
    for slide in deck.slides:
        _align_slide_text_to_visual(slide)
        slide.headline = _limit_words(soften_unsupported_impact_claim(slide.headline), max_words=14, max_chars=92)
        if slide.slide_role in {"recommendations", "limitations"}:
            slide.main_message = _plain_limit(slide.main_message, max_words=20, max_chars=150)
        else:
            slide.main_message = _limit_words(soften_unsupported_impact_claim(slide.main_message), max_words=24, max_chars=170)
        slide.subtitle = shorten(slide.subtitle, 120)
        for block in slide.content_blocks:
            max_chars = 190 if block.type == "recommendations" else 126
            if block.type in {"recommendations", "limitations"}:
                block.items = _dedupe_text_items(
                    _plain_limit(item, max_words=34 if block.type == "recommendations" else 14, max_chars=max_chars)
                    for item in block.items
                )
            else:
                block.items = _dedupe_text_items(
                    _limit_words(soften_unsupported_impact_claim(item), max_words=18, max_chars=max_chars)
                    for item in block.items
                )
        if slide.visual and slide.visual.chart_type == "decision_tree":
            data = slide.visual.data if isinstance(slide.visual.data, dict) else {}
            note = _decision_tree_caveat(slide.visual)
            if note:
                slide.visual.takeaway = _limit_words(note, max_words=24, max_chars=170)
                if not slide.main_message or "baseline" in note.lower():
                    slide.main_message = _limit_words(note, max_words=24, max_chars=170)


def _legacy_visual_can_attach(visual: VisualSpec, slide: SlideSpec) -> bool:
    if slide.slide_role == "analysis":
        return True
    if visual.type in {"structured_chart", "chart", "code_figure"} or visual.chart_type == "decision_tree":
        return _slide_matches_visual(slide, visual)
    return visual.type in {"image", "legacy_image_fallback"}


def _align_slide_text_to_visual(slide: SlideSpec) -> None:
    visual = slide.visual
    if not visual:
        return
    if visual.type not in {"structured_chart", "chart", "code_figure"} and visual.chart_type != "decision_tree":
        return
    if visual.chart_type == "decision_tree":
        headline = _decision_tree_visual_headline(visual)
        data = visual.data if isinstance(visual.data, dict) else {}
        note = _decision_tree_caveat(visual)
        if headline:
            slide.headline = headline
            visual.finding = headline
        if note:
            visual.takeaway = note
            slide.main_message = note
        elif visual.takeaway:
            slide.main_message = visual.takeaway
        if slide.content_blocks:
            items = [item for item in (headline, note or visual.takeaway, visual.title) if compact_whitespace(item)]
            slide.content_blocks[0].items = _dedupe_text_items(items)
        return
    evidence_text = _visual_evidence_text(visual)
    if not evidence_text:
        return
    if visual.type == "code_figure" and _headline_has_unsupported_ratio(slide.headline, evidence_text):
        slide.headline = refine_headline("", evidence_text)
    elif not _headlines_overlap(slide.headline, evidence_text):
        slide.headline = refine_headline("", evidence_text)
    if slide.main_message and _headlines_overlap(slide.main_message, evidence_text):
        return
    slide.main_message = shorten(first_nonempty(visual.finding, visual.takeaway, visual.title, evidence_text), 170)


def _slide_matches_visual(slide: SlideSpec, visual: VisualSpec) -> bool:
    slide_text = " ".join(
        [
            compact_whitespace(slide.headline),
            compact_whitespace(slide.main_message),
            " ".join(item for block in slide.content_blocks for item in block.items),
        ]
    )
    return _headlines_overlap(slide_text, _visual_evidence_text(visual))


def _visual_evidence_text(visual: VisualSpec) -> str:
    data_text = ""
    if isinstance(visual.data, dict):
        data_text = " ".join(
            compact_whitespace(visual.data.get(key))
            for key in ("performance_note", "metric_label", "target", "target_column")
            if compact_whitespace(visual.data.get(key))
        )
    return first_nonempty(visual.finding, visual.takeaway, visual.title, data_text)


def _decision_tree_visual_headline(visual: VisualSpec) -> str:
    data = visual.data if isinstance(visual.data, dict) else {}
    nodes = data.get("nodes", []) if isinstance(data, dict) else []
    source_ids = {
        compact_whitespace(edge.get("source") or edge.get("from") or edge.get("parent"))
        for edge in data.get("edges", [])
        if isinstance(edge, dict)
    }
    features: list[str] = []
    for node in nodes:
        if not isinstance(node, dict):
            continue
        node_id = compact_whitespace(node.get("id") or node.get("node_id") or node.get("name"))
        if compact_whitespace(node.get("type")).lower() != "split" and node_id not in source_ids:
            continue
        feature = compact_whitespace(node.get("feature"))
        if not feature:
            label = compact_whitespace(node.get("label") or node.get("rule"))
            feature = re_split_feature(label)
        feature = _clean_tree_feature_name(feature)
        key = feature.lower()
        if feature and key not in {item.lower() for item in features}:
            features.append(feature)
        if len(features) >= 3:
            break
    if features:
        joined = _join_short_list(features)
        note = _decision_tree_caveat(visual).lower()
        prefix = "Exploratory tree splits" if any(token in note for token in ("explanatory", "baseline", "imbalance", "precision")) else "Decision tree splits"
        return f"{prefix} on {joined}"
    return first_nonempty(visual.title, "Decision tree rules summarize model logic")


def _decision_tree_caveat(visual: VisualSpec | None) -> str:
    if not visual:
        return ""
    data = visual.data if isinstance(visual.data, dict) else {}
    return first_nonempty(
        decision_tree_imbalance_note(data),
        data.get("performance_note"),
        decision_tree_performance_note(data),
        "Exploratory screening only: validate precision, recall, F1, and support before operational use.",
    )


def _decision_tree_visual(workflow_state: dict[str, Any]) -> VisualSpec | None:
    analysis = workflow_state.get("analysis_results", {}) or {}
    for artifact in list(analysis.get("analysis_artifacts", []) or []) + list(analysis.get("chart_specs", []) or []):
        if isinstance(artifact, dict) and compact_whitespace(artifact.get("chart_type")).lower() == "decision_tree":
            visual = VisualSpec.from_any({"type": "structured_chart", **artifact})
            if visual and isinstance(visual.data, dict):
                target = compact_whitespace(workflow_state.get("decision_tree_target_column"))
                if target and not compact_whitespace(visual.data.get("target") or visual.data.get("target_column")):
                    visual.data["target"] = target
            return visual
    return None


def _decision_tree_rule_callouts(visual: VisualSpec | None, limit: int = 3) -> list[str]:
    if not visual or not isinstance(visual.data, dict):
        return []
    nodes = [node for node in visual.data.get("nodes", []) if isinstance(node, dict)]
    edges = [edge for edge in visual.data.get("edges", []) if isinstance(edge, dict)]
    parent_by_child = {compact_whitespace(edge.get("target") or edge.get("to") or edge.get("child")): edge for edge in edges}
    node_by_id = {compact_whitespace(node.get("id") or node.get("node_id") or node.get("name")): node for node in nodes}
    callouts: list[str] = []
    for node_id, node in node_by_id.items():
        if compact_whitespace(node.get("type")).lower() != "leaf" and "predict" not in compact_whitespace(node.get("label")).lower():
            continue
        edge = parent_by_child.get(node_id, {})
        parent = node_by_id.get(compact_whitespace(edge.get("source") or edge.get("from") or edge.get("parent")), {})
        condition = compact_whitespace(edge.get("condition") or edge.get("label"))
        split = compact_whitespace(parent.get("label") or parent.get("rule"))
        prediction = compact_whitespace(node.get("prediction") or node.get("label") or node.get("rule"))
        text = " | ".join(part for part in (split, condition, prediction) if part)
        if text:
            callouts.append(text)
        if len(callouts) >= limit:
            break
    if callouts:
        return [_business_rule_callout(callout, visual) for callout in callouts]
    rules = visual.data.get("rules", [])
    return [_business_rule_callout(rule, visual) for rule in rules if compact_whitespace(rule)][:limit]


