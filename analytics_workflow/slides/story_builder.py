def _business_rule_callout(rule: Any, visual: VisualSpec) -> str:
    text = compact_whitespace(rule)
    if not text:
        return ""
    text = re.sub(r"\bIf\s+", "", text, flags=re.IGNORECASE)
    text = re.sub(r"\bthen\s+predict\s+", "=> predicted ", text, flags=re.IGNORECASE)
    text = text.replace("[Default]", "higher default risk").replace("[No Default]", "lower default risk")
    text = re.sub(r"\[(1|Yes|True)\]", "higher default risk", text, flags=re.IGNORECASE)
    text = re.sub(r"\[(0|No|False)\]", "lower default risk", text, flags=re.IGNORECASE)
    text = text.replace("_", " ")
    text = re.sub(r"\s+", " ", text).strip(" .")
    target = compact_whitespace(visual.data.get("target") if isinstance(visual.data, dict) else "").lower()
    if any(token in target for token in ("loan", "default", "credit")):
        text = _credit_rule_language(text)
    return shorten(text, 138, placeholder="")


def _credit_rule_language(text: str) -> str:
    replacements = {
        "loan percent income": "debt burden",
        "loan percent income": "debt burden",
        "loan_percent_income": "debt burden",
        "loan int rate": "interest rate",
        "loan_int_rate": "interest rate",
        "person income": "borrower income",
        "person_income": "borrower income",
        "loan grade": "loan grade",
        "loan_grade": "loan grade",
        "person home ownership": "home ownership",
        "person_home_ownership": "home ownership",
        "cb person default on file": "prior default flag",
        "cb_person_default_on_file": "prior default flag",
    }
    clean = text
    for source, replacement in replacements.items():
        clean = re.sub(source, replacement, clean, flags=re.IGNORECASE)
    clean = re.sub(r"borrower income\s*<=\s*(\d+(?:\.\d+)?)", lambda m: f"borrower income at or below ${float(m.group(1)):,.0f}", clean, flags=re.IGNORECASE)
    clean = re.sub(r"borrower income\s*>\s*(\d+(?:\.\d+)?)", lambda m: f"borrower income above ${float(m.group(1)):,.0f}", clean, flags=re.IGNORECASE)
    clean = re.sub(r"debt burden\s*<=\s*(\d+(?:\.\d+)?)", r"debt burden at or below \1", clean, flags=re.IGNORECASE)
    clean = re.sub(r"debt burden\s*>\s*(\d+(?:\.\d+)?)", r"debt burden above \1", clean, flags=re.IGNORECASE)
    clean = clean.replace("<=", "at or below").replace(">=", "at least").replace(">", "above").replace("<", "below")
    return compact_whitespace(clean)


def _decision_tree_split_features_from_visual(visual: VisualSpec) -> list[str]:
    data = visual.data if isinstance(visual.data, dict) else {}
    nodes = data.get("nodes", []) if isinstance(data, dict) else []
    source_ids = {
        compact_whitespace(edge.get("source") or edge.get("from") or edge.get("parent"))
        for edge in data.get("edges", [])
        if isinstance(edge, dict)
    }
    features: list[str] = []
    for node in nodes:
        if not isinstance(node, dict):
            continue
        node_id = compact_whitespace(node.get("id") or node.get("node_id") or node.get("name"))
        if compact_whitespace(node.get("type")).lower() != "split" and node_id not in source_ids:
            continue
        feature = compact_whitespace(node.get("feature")) or re_split_feature(compact_whitespace(node.get("label") or node.get("rule")))
        feature = _clean_tree_feature_name(feature)
        if feature and feature.lower() not in {item.lower() for item in features}:
            features.append(feature)
        if len(features) >= 3:
            break
    return features


def _remove_unverified_ratio_claim(text: Any) -> str:
    clean = compact_whitespace(text)
    return re.sub(r"\b\d+(?:\.\d+)?x\s+(?:higher|lower|greater|larger|smaller)\b", "different", clean, flags=re.IGNORECASE)


def re_split_feature(label: str) -> str:
    for marker in ("<=", ">=", "<", ">", "="):
        if marker in label:
            return compact_whitespace(label.split(marker, 1)[0])
    return ""


def _clean_tree_feature_name(feature: str) -> str:
    text = compact_whitespace(feature).replace("_", " ")
    for suffix in (" Yes", " No", " True", " False", " 1", " 0"):
        if text.endswith(suffix):
            text = text[: -len(suffix)]
            break
    return compact_whitespace(text)


def _join_short_list(items: list[str]) -> str:
    if len(items) <= 1:
        return items[0] if items else ""
    if len(items) == 2:
        return f"{items[0]} and {items[1]}"
    return f"{', '.join(items[:-1])}, and {items[-1]}"


def _limit_words(value: Any, *, max_words: int, max_chars: int) -> str:
    text = soften_unsupported_impact_claim(value)
    if not text:
        return ""
    words = text.split()
    if len(words) > max_words:
        text = " ".join(words[:max_words]).rstrip(".,;:")
        if text:
            text += "."
    return shorten(text, max_chars)


def _plain_limit(value: Any, *, max_words: int, max_chars: int) -> str:
    text = soften_unsupported_impact_claim(value).rstrip(".")
    if not text:
        return ""
    words = text.split()
    if len(words) > max_words:
        text = " ".join(words[:max_words]).rstrip(".,;:")
    if len(text) > max_chars:
        text = text[:max_chars].rsplit(" ", 1)[0].rstrip(".,;:")
    return compact_whitespace(text)


